package com.github.h3yow.zerotrustgatewayjava.gateway;

/**
 * 所有可区分的拒绝原因。
 */
public enum RejectionReason {
    // 鉴权类
    MISSING_CREDENTIAL,
    UNKNOWN_CREDENTIAL_TYPE,
    MALFORMED_CREDENTIAL,
    SIGNATURE_MISMATCH,
    CREDENTIAL_EXPIRED,
    CREDENTIAL_NOT_YET_VALID,
    CREDENTIAL_REVOKED,
    PRINCIPAL_MISMATCH,
    // 重放 / 篡改类
    MISSING_REQUEST_ID,
    MISSING_TIMESTAMP,
    TIMESTAMP_OUT_OF_WINDOW,
    REPLAYED_REQUEST,
    SEQUENCE_REGRESSION,
    REPLAY_CAPACITY_EXCEEDED,
    // 限流类
    RATE_LIMITED
}
